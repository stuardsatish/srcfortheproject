-- 5 -- order-level refunds (internal builder + the two RPCs) --------------------------------------------------------------------------------------------
-- The caller holds the ORDER row lock. NULL amount = everything that can still be refunded. The M5 cap trigger is the last line of defence.
create or replace function public.app_create_order_refund(
  p_order_id text, p_request_id uuid, p_amount numeric, p_method text, p_key text, p_reason text, p_note text, p_actor uuid)
returns public.refunds
language plpgsql security definer
set search_path = public, pg_catalog
as $$
declare
  o         public.orders;
  f         public.refunds;
  v_refunded numeric;
  v_remaining numeric;
  v_amount  numeric;
begin
  select * into o from public.orders where id = p_order_id;
  if not found then raise exception 'Order not found' using errcode = 'P0002'; end if;
  if lower(btrim(coalesce(o.payment_status, ''))) <> 'paid' then
    raise exception 'This order is not marked as paid, so there is nothing to refund' using errcode = '22023', detail = 'NOT_PAID';
  end if;
  if p_method is null or p_method not in ('razorpay', 'manual') then raise exception 'The refund method must be razorpay or manual' using errcode = '22023'; end if;
  if p_method = 'razorpay' and (coalesce(o.razorpay_payment_id, '') = '' or lower(coalesce(o.payment_method, '')) <> 'razorpay') then
    raise exception 'This order was not paid through Razorpay, so it cannot be refunded through the gateway - choose a manual refund' using errcode = '22023', detail = 'NOT_RAZORPAY';
  end if;
  select coalesce(sum(x.amount), 0) into v_refunded from public.refunds x where x.order_id = o.id and x.status in ('pending', 'succeeded');
  v_remaining := coalesce(o.total, 0) - v_refunded;
  v_amount := round(coalesce(p_amount, v_remaining), 2);
  if v_amount <= 0 then raise exception 'The refund amount must be greater than zero' using errcode = '22023', detail = 'AMOUNT_NOT_POSITIVE'; end if;
  if v_amount > v_remaining + 0.005 then
    raise exception 'The refund (%) is more than what can still be refunded for this order (%)', v_amount, greatest(v_remaining, 0) using errcode = '22023', detail = 'EXCEEDS_PAID';
  end if;
  insert into public.refunds (refund_no, order_id, request_id, kind, amount, items_amount, shipping_amount, adjustment_amount, method, status, gateway_state, idempotency_key, reason)
  values (public.app_next_refund_no(), o.id, p_request_id, 'order', v_amount, v_amount, 0, 0, p_method, 'pending', case when p_method = 'razorpay' then 'not_sent' end, p_key, p_reason)
  returning * into f;
  insert into public.refund_private (refund_id, internal_note, initiated_by) values (f.id, nullif(btrim(coalesce(p_note, '')), ''), p_actor);
  insert into public.refund_events (refund_id, event_type, to_status, actor_id, actor_role, note)
  values (f.id, 'created', 'pending', p_actor, 'admin', format('%s refund of %s %s (%s)', p_method, f.amount, f.currency, coalesce(p_reason, 'order refund')));
  return f;
end;
$$;

create or replace function public.create_order_refund(
  p_order_id        text,
  p_amount          numeric,
  p_method          text,
  p_reason          text,                    -- what the customer reads ("the item you returned", "goodwill")
  p_idempotency_key text,
  p_request_id      uuid default null,       -- an EXCHANGE request of this order the money settles (cancelled after the returned item was accepted)
  p_note            text default null)       -- staff only
returns jsonb
language plpgsql security definer
set search_path = public, pg_catalog
as $$
declare
  v_uid    uuid := auth.uid();
  o        public.orders;
  f        public.refunds;
  rq       public.return_requests;
  v_key    text := nullif(btrim(coalesce(p_idempotency_key, '')), '');
  v_reason text := nullif(btrim(coalesce(p_reason, '')), '');
begin
  if v_uid is null or not public.app_is_admin() then raise exception 'Admin access required' using errcode = '42501'; end if;
  select * into o from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found' using errcode = 'P0002'; end if;
  if v_key is null or char_length(v_key) not between 8 and 100 then raise exception 'An idempotency key of 8 to 100 characters is required' using errcode = '22023'; end if;
  select * into f from public.refunds where idempotency_key = v_key;
  if found then                                                       -- a retry (double click, lost response) returns the same refund
    if f.order_id <> o.id or f.kind <> 'order' then raise exception 'This idempotency key belongs to another refund' using errcode = '22023'; end if;
    return jsonb_build_object('ok', true, 'created', false, 'refund_id', f.id, 'refund_no', f.refund_no, 'status', f.status, 'amount', f.amount, 'method', f.method);
  end if;
  if v_reason is null or char_length(v_reason) not between 3 and 300 then raise exception 'Say what the refund is for (3 to 300 characters, the customer reads it)' using errcode = '22023'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Enter the amount to refund' using errcode = '22023'; end if;
  if nullif(btrim(coalesce(p_note, '')), '') is not null and char_length(btrim(p_note)) > 1000 then raise exception 'The note is too long (1000 characters at most)' using errcode = '22023'; end if;
  if p_request_id is not null then
    select * into rq from public.return_requests where id = p_request_id and order_id = o.id;
    if not found then raise exception 'That request does not belong to this order' using errcode = '22023'; end if;
    if rq.type <> 'exchange' then raise exception 'A return is refunded with its own refund (create_refund); this tool is for an exchange that was cancelled after the item came back' using errcode = '22023'; end if;
  end if;

  f := public.app_create_order_refund(o.id, p_request_id, p_amount, p_method, v_key, v_reason, p_note, v_uid);
  perform public.app_notify_refund(f.id, 'Your refund is being prepared', format('%s · ₹%s is being refunded: %s.', f.refund_no, f.amount, v_reason));
  if p_request_id is not null then
    insert into public.return_request_events (request_id, actor_id, actor_role, note)
    values (p_request_id, v_uid, 'admin', format('A refund of ₹%s (%s) is being prepared.', f.amount, v_reason));
  end if;
  return jsonb_build_object('ok', true, 'created', true, 'refund_id', f.id, 'refund_no', f.refund_no, 'status', f.status, 'amount', f.amount, 'method', f.method);
end;
$$;

-- 6 -- cancel_order -------------------------------------------------------------------------------------------------------------------------------
create or replace function public.cancel_order(
  p_order_id        text,
  p_reason          text,                    -- the customer reads it
  p_refund_method   text default null,       -- required when the order was paid: 'razorpay' | 'manual'
  p_idempotency_key text default null,       -- required when the order was paid (the refund is created with it)
  p_internal_note   text default null)       -- staff only
returns jsonb
language plpgsql security definer
set search_path = public, pg_catalog
as $$
declare
  v_uid      uuid := auth.uid();
  o          public.orders;
  c          record;
  f          public.refunds;
  v_ex       public.order_cancellations;
  v_status   text;
  v_reason   text := nullif(btrim(coalesce(p_reason, '')), '');
  v_note     text := nullif(btrim(coalesce(p_internal_note, '')), '');
  v_key      text := nullif(btrim(coalesce(p_idempotency_key, '')), '');
  v_paid     boolean;
  v_restored jsonb := '[]'::jsonb;
  v_ref      text;
  v_body     text;
begin
  if v_uid is null or not public.app_is_admin() then raise exception 'Admin access required' using errcode = '42501'; end if;
  select * into o from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found' using errcode = 'P0002'; end if;

  -- a second call (double click, lost response) returns the first result: nothing is restocked or refunded twice
  select * into v_ex from public.order_cancellations where order_id = o.id;
  if found then
    return jsonb_build_object('ok', true, 'already', true, 'order_status', o.order_status, 'refund_id', v_ex.refund_id, 'stock_restored', v_ex.stock_restored);
  end if;
  v_status := lower(btrim(coalesce(o.order_status, '')));
  if v_status = 'cancelled' then
    return jsonb_build_object('ok', true, 'already', true, 'legacy', true, 'order_status', o.order_status);       -- cancelled before this record existed
  end if;
  if v_status = 'shipped' then
    raise exception 'This order is already on its way, so it cannot be cancelled. If it cannot be stopped, wait for the delivery: the customer can then return or exchange it.' using errcode = '22023', detail = 'ALREADY_SHIPPED';
  end if;
  if v_status = 'delivered' then
    raise exception 'This order was delivered, so it cannot be cancelled: the customer returns or exchanges it (see the return and exchange requests).' using errcode = '22023', detail = 'ALREADY_DELIVERED';
  end if;
  if v_status not in ('pending', 'placed', 'confirmed') then
    raise exception 'An order that is "%" cannot be cancelled', coalesce(o.order_status, '(no status)') using errcode = '22023';
  end if;
  if exists (select 1 from public.shipments s where s.order_id = o.id and s.direction = 'outbound' and s.status <> 'cancelled') then
    raise exception 'This order has a shipment on record: cancel the shipment first' using errcode = '22023', detail = 'HAS_SHIPMENT';
  end if;
  if v_reason is null or char_length(v_reason) > 500 then raise exception 'Give the customer a reason (1 to 500 characters)' using errcode = '22023'; end if;
  if v_note is not null and char_length(v_note) > 1000 then raise exception 'The note is too long (1000 characters at most)' using errcode = '22023'; end if;
  v_paid := lower(btrim(coalesce(o.payment_status, ''))) = 'paid';
  if v_paid then
    if p_refund_method is null or p_refund_method not in ('razorpay', 'manual') then
      raise exception 'This order was paid: choose how it is refunded (razorpay or manual)' using errcode = '22023', detail = 'REFUND_METHOD_REQUIRED';
    end if;
    if v_key is null or char_length(v_key) not between 8 and 100 then raise exception 'An idempotency key of 8 to 100 characters is required to refund a paid order' using errcode = '22023'; end if;
    if exists (select 1 from public.refunds x where x.idempotency_key = v_key) then raise exception 'This idempotency key belongs to another refund' using errcode = '22023'; end if;
  end if;

  -- 1) the order (the generic "order cancelled" notification is replaced by the richer one below)
  perform set_config('app.skip_order_notify', 'on', true);
  update public.orders set order_status = 'cancelled', updated_at = now() where id = o.id;
  perform set_config('app.skip_order_notify', 'off', true);

  -- 2) the stock THIS ORDER took (the ledger's sale rows are the evidence), back to the counters it came from, once.
  --    Fixed (product, variant) order = the order create_order_tx locks in: two cancellations never lock in opposite order.
  for c in
    select l.product_id, l.variant_id, (-sum(l.change))::integer as deducted
      from public.inventory_logs l
     where l.order_id = o.id and l.movement_type = 'sale' and l.bucket = 'sellable'
     group by l.product_id, l.variant_id
    having -sum(l.change) > 0
     order by l.product_id, l.variant_id
  loop
    begin
      perform public.apply_inventory_movement(c.product_id, c.variant_id, c.deducted, 'cancel_restock', o.id, 'order', o.id,
                'Order cancelled before shipment', v_uid, 'admin', 'cancel:' || o.id || ':' || c.product_id || ':' || c.variant_id);
      v_restored := v_restored || jsonb_build_array(jsonb_build_object('product_id', c.product_id, 'variant_id', c.variant_id, 'quantity', c.deducted));
    exception when sqlstate 'P0002' then
      raise warning 'order % : % / % no longer exists, its stock cannot be restored', o.id, c.product_id, c.variant_id;
    end;
  end loop;

  -- 3) the money: a paid order is refunded IN FULL through the normal refund steps (nothing is paid out here)
  if v_paid then
    f := public.app_create_order_refund(o.id, null, null, p_refund_method, v_key, 'your cancelled order', v_note, v_uid);
  end if;

  -- 4) the linked record + the customer
  insert into public.order_cancellations (order_id, reason, refund_id, stock_restored) values (o.id, v_reason, f.id, v_restored);
  insert into public.order_cancellation_private (order_id, cancelled_by, internal_note) values (o.id, v_uid, v_note);
  if o.user_id is not null then
    begin
      v_ref := upper(right(o.id::text, 8));
      v_body := 'Order #' || v_ref || ' has been cancelled. ' || v_reason
                || case when f.id is not null then format(' A refund of ₹%s is being prepared (%s).', f.amount, f.refund_no) else '' end;
      perform public.app_queue_notification(o.user_id, 'order_update', 'Order cancelled', v_body,
        jsonb_build_object('type', 'order', 'orderId', o.id, 'status', 'cancelled', 'refundId', f.id));
    exception when others then
      raise warning 'cancellation notification skipped: %', sqlerrm;
    end;
  end if;
  return jsonb_build_object('ok', true, 'already', false, 'order_status', 'cancelled', 'stock_restored', v_restored,
                            'refund_id', f.id, 'refund_no', f.refund_no, 'refund_amount', f.amount, 'refund_method', f.method);
end;
$$;

-- 7 -- what each stage permits ---------------------------------------------------------------------------------------------------------------------
-- The documented matrix (DATABASE_CHANGE_PLAN 4i) as one admin call; the screens use it to show or hide a button, the functions above enforce it.
create or replace function public.get_order_operations(p_order_id text)
returns jsonb
language plpgsql stable security definer
set search_path = public, pg_catalog
as $$
declare
  o         public.orders;
  v_status  text;
  v_active  integer;
  v_left    integer;
  v_paid    boolean;
  v_refunded numeric;
  v_remaining numeric;
  v_stage   text;
begin
  if auth.uid() is null or not public.app_is_admin() then raise exception 'Admin access required' using errcode = '42501'; end if;
  select * into o from public.orders where id = p_order_id;
  if not found then raise exception 'Order not found' using errcode = 'P0002'; end if;
  v_status := lower(btrim(coalesce(o.order_status, '')));
  select count(*) into v_active from public.shipments s where s.order_id = o.id and s.direction = 'outbound' and s.status <> 'cancelled';
  select coalesce(sum(public.app_order_item_remaining(oi.id)), 0)::integer into v_left from public.order_items oi where oi.order_id = o.id;
  v_paid := lower(btrim(coalesce(o.payment_status, ''))) = 'paid';
  select coalesce(sum(x.amount), 0) into v_refunded from public.refunds x where x.order_id = o.id and x.status in ('pending', 'succeeded');
  v_remaining := greatest(coalesce(o.total, 0) - v_refunded, 0);
  v_stage := case when v_status in ('pending', 'placed', 'confirmed') then 'before_shipment' when v_status = 'shipped' then 'in_transit'
                  when v_status = 'delivered' then 'delivered' when v_status = 'cancelled' then 'cancelled' else 'unknown' end;
  return jsonb_build_object(
    'order_id', o.id, 'stage', v_stage, 'order_status', o.order_status, 'payment_status', o.payment_status,
    'cancel', jsonb_build_object('allowed', v_stage = 'before_shipment' and v_active = 0,
      'reason', case v_stage when 'before_shipment' then case when v_active = 0 then '' else 'A shipment is on record: cancel the shipment first' end
                             when 'in_transit' then 'The order is on its way: it cannot be cancelled; once delivered the customer can return or exchange it'
                             when 'delivered' then 'The order was delivered: use the return / exchange workflow'
                             when 'cancelled' then 'The order is already cancelled' else 'Not available for this status' end),
    'ship', jsonb_build_object('allowed', v_stage in ('before_shipment', 'in_transit') and v_left > 0,
      'reason', case when v_stage not in ('before_shipment', 'in_transit') then 'Only an order that is not delivered or cancelled can be shipped'
                     when v_left = 0 then 'Every unit is already on a shipment' else '' end),
    'mark_delivered', jsonb_build_object('allowed', v_stage = 'in_transit', 'reason', case when v_stage = 'in_transit' then '' else 'Only a shipped order can be marked delivered' end),
    'return_exchange', jsonb_build_object('allowed', v_stage = 'delivered', 'reason', case when v_stage = 'delivered' then 'Started by the customer within the policy window (see get_order_eligibility)' else 'Available after delivery' end),
    'order_refund', jsonb_build_object('allowed', v_paid and v_remaining > 0, 'remaining', v_remaining,
      'reason', case when not v_paid then 'The order is not marked as paid' when v_remaining <= 0 then 'Everything paid was already refunded or is being refunded' else '' end),
    'refunded_so_far', v_refunded);
end;
$$;

-- 8 -- a payment that could not become an order (known issue K-8) ----------------------------------------------------------------------------------------
-- Orders are created only AFTER Razorpay captured the payment (payment-verify / payment-webhook -> create_order_tx). When the last unit sold out in the
-- meantime create_order_tx refuses ("Insufficient stock ...") and, until now, the money stayed captured with no order and no trace. The Edge Functions now
-- call record_payment_exception (service role) in that case; the admin sees the row, refunds the payment in the Razorpay dashboard (there is no order to
-- hang a refunds row on) and records it with resolve_payment_exception. The customer gets ONE notification. A failed / abandoned payment (nothing captured)
-- creates no order, no stock movement and no row here - there is nothing to undo.
create table if not exists public.payment_exceptions (
  id                  uuid          primary key default gen_random_uuid(),
  razorpay_order_id   text          not null unique,
  razorpay_payment_id text          not null unique,
  user_id             uuid          references public.profiles (id) on delete set null,
  amount              numeric(12,2) not null check (amount >= 0),
  reason              text          not null check (char_length(reason) <= 500),                 -- what the database said (staff only)
  items               jsonb         not null default '[]'::jsonb,                                -- what the customer wanted
  status              text          not null default 'open' check (status in ('open', 'refunded', 'resolved')),
  refund_reference    text          check (refund_reference is null or char_length(refund_reference) <= 200),
  resolution_note     text          check (resolution_note is null or char_length(resolution_note) <= 1000),
  resolved_by         uuid          references public.profiles (id) on delete set null,
  resolved_at         timestamptz,
  created_at          timestamptz   not null default now(),
  constraint payment_exceptions_resolved_chk check ((status = 'open') = (resolved_at is null))
);
create index if not exists payment_exceptions_status_idx on public.payment_exceptions (status, created_at desc);
alter table public.payment_exceptions enable row level security;
revoke all on public.payment_exceptions from anon, authenticated;
grant select on public.payment_exceptions to authenticated;
drop policy if exists payment_exceptions_select on public.payment_exceptions;
create policy payment_exceptions_select on public.payment_exceptions for select to authenticated using (public.app_is_admin());

-- service role only (the Edge Functions); idempotent per payment id; the admins and the customer are told once
create or replace function public.record_payment_exception(
  p_razorpay_order_id text, p_razorpay_payment_id text, p_user_id uuid, p_amount numeric, p_reason text, p_items jsonb default '[]'::jsonb)
returns jsonb
language plpgsql security definer
set search_path = public, pg_catalog
as $$
declare
  v_id uuid;
  v_amt numeric := round(coalesce(p_amount, 0), 2);
begin
  if not public.app_is_service_role() then raise exception 'Service role only' using errcode = '42501'; end if;
  if nullif(btrim(coalesce(p_razorpay_order_id, '')), '') is null or nullif(btrim(coalesce(p_razorpay_payment_id, '')), '') is null then
    raise exception 'The Razorpay order and payment ids are required' using errcode = '22023';
  end if;
  insert into public.payment_exceptions (razorpay_order_id, razorpay_payment_id, user_id, amount, reason, items)
  values (btrim(p_razorpay_order_id), btrim(p_razorpay_payment_id), p_user_id, greatest(v_amt, 0), left(coalesce(nullif(btrim(coalesce(p_reason, '')), ''), 'The order could not be created'), 500),
          case when jsonb_typeof(p_items) = 'array' then p_items else '[]'::jsonb end)
  on conflict (razorpay_payment_id) do nothing
  returning id into v_id;
  if v_id is null then return jsonb_build_object('ok', true, 'recorded', false); end if;           -- the same payment again (a webhook retry): nothing more to do
  begin
    perform public.app_notify_admins('A paid order could not be created', format('₹%s was captured but the order failed: %s', v_amt, left(coalesce(p_reason, ''), 120)),
      jsonb_build_object('type', 'admin_payment_exception', 'paymentExceptionId', v_id, 'razorpayPaymentId', p_razorpay_payment_id));
    if p_user_id is not null then
      perform public.app_queue_notification(p_user_id, 'order_update', 'We could not complete your order',
        format('Your payment of ₹%s went through, but an item sold out before your order could be confirmed. We will refund it in full - there is nothing you need to do.', v_amt),
        jsonb_build_object('type', 'payment_exception', 'paymentExceptionId', v_id));
    end if;
  exception when others then
    raise warning 'payment exception notification skipped: %', sqlerrm;       -- never lose the record because a notification failed
  end;
  return jsonb_build_object('ok', true, 'recorded', true, 'id', v_id);
end;
$$;

-- the admin closes it: "refunded" (the payment was refunded in the Razorpay dashboard - the reference is required) or "resolved" (handled another way, e.g. the
-- order was created by hand - a note is required)
create or replace function public.resolve_payment_exception(p_id uuid, p_status text, p_reference text default null, p_note text default null)
returns jsonb
language plpgsql security definer
set search_path = public, pg_catalog
as $$
declare
  v_uid  uuid := auth.uid();
  e      public.payment_exceptions;
  v_ref  text := nullif(btrim(coalesce(p_reference, '')), '');
  v_note text := nullif(btrim(coalesce(p_note, '')), '');
begin
  if v_uid is null or not public.app_is_admin() then raise exception 'Admin access required' using errcode = '42501'; end if;
  select * into e from public.payment_exceptions where id = p_id for update;
  if not found then raise exception 'Payment record not found' using errcode = 'P0002'; end if;
  if p_status is null or p_status not in ('refunded', 'resolved') then raise exception 'The status must be refunded or resolved' using errcode = '22023'; end if;
  if e.status = p_status then return jsonb_build_object('ok', true, 'already', true, 'status', e.status); end if;
  if e.status <> 'open' then raise exception 'This payment was already closed as "%"', e.status using errcode = '22023'; end if;
  if p_status = 'refunded' and v_ref is null then raise exception 'Enter the Razorpay refund id (or the bank reference) of the refund you made' using errcode = '22023'; end if;
  if p_status = 'resolved' and v_note is null then raise exception 'Say how this was handled' using errcode = '22023'; end if;
  if v_ref is not null and char_length(v_ref) > 200 then raise exception 'The reference is too long (200 characters at most)' using errcode = '22023'; end if;
  if v_note is not null and char_length(v_note) > 1000 then raise exception 'The note is too long (1000 characters at most)' using errcode = '22023'; end if;
  update public.payment_exceptions set status = p_status, refund_reference = v_ref, resolution_note = v_note, resolved_by = v_uid, resolved_at = now() where id = p_id;
  return jsonb_build_object('ok', true, 'already', false, 'status', p_status);
end;
$$;

