-- ============================================================================
-- M6 — INVENTORY CONSISTENCY and ORDER CANCELLATION (IMPLEMENTATION_PLAN Phases 11-12; requires M5b)
--
-- PHASE 11 — what happens to STOCK after a return is physically received and inspected:
--   * A return / exchange REQUEST and its approval never touch stock (unchanged since M4).
--   * The moment the admin records the INSPECTION of a returned line, its units go exactly one of three ways (the admin chooses per line,
--     `disposition`; the default follows the result):
--       restock    sellable stock + qty on the order line's OWN counter (variant counter / main counter), ledger `return_restock`   [default for PASSED]
--       unsellable the units are KEPT but can never be sold: ledger `return_unsellable` in the `unsellable` bucket, sellable stock unchanged [default for FAILED;
--                  also allowed for a PASSED line that is refunded / exchanged but is damaged or defective]
--       none       no stock record (the failed parcel is sent back to the customer / was never ours)                                   [FAILED only]
--     Idempotent: ledger keys retrestock:<line> / retunsell:<line> and the line remembers what was done (`stock_effect`); a line inspected
--     before this migration keeps `stock_effect` NULL (it was never restocked - correct that by hand with the product form's stock field).
--     A refund failing, retrying or being voided never moves stock (money and stock are separate steps).
--   * New admin reports: `inventory_unsellable_summary()` (units kept as unsellable per option), `inventory_reconcile()` (the sellable counter vs
--     what the ledger says it should be after its last movement: a drift means stock was changed without the ledger), `inventory_gaps()`
--     (every place where two consecutive ledger rows of an option do not follow each other). `inventory_logs.seq` gives the ledger a strict order.
--
-- PHASE 12 — order cancellation and the permitted-operation matrix:
--   * cancel_order(order, reason, refund method, idempotency key, note)  ADMIN, before shipment only (pending / placed / confirmed and no active
--     outbound shipment). In ONE transaction: status -> cancelled; the stock THIS ORDER deducted (the ledger's `sale` rows are the evidence) goes back
--     to the counters it came from, exactly once (`cancel_restock`, key cancel:<order>:<product>:<variant>); a PAID order gets an order-level refund
--     (refunds.kind = 'order', the whole amount still refundable, sent / recorded with the M5 refund RPCs and Edge Function); the customer gets ONE
--     notification; a linked record `order_cancellations` (+ staff-only `order_cancellation_private`) keeps who / why / what stock came back.
--     A shipped or delivered order is REFUSED with a pointer to the return workflow; cancelling twice returns the first result.
--   * create_order_refund(order, amount, method, reason, key, request, note)  ADMIN, any paid order, up to what is still refundable: the tool for a
--     cancelled order's failed refund and for an exchange cancelled AFTER the returned item was accepted (known limitation K-10 of M5b).
--   * get_order_operations(order)  ADMIN: what each stage permits (cancel / ship / mark delivered / return-exchange / order refund) and why not.
--   * payment_exceptions + record_payment_exception (service role: the payment Edge Functions) + resolve_payment_exception (admin): a payment that
--     was CAPTURED but could not become an order because the last unit sold out meanwhile (known issue K-8) is recorded for the admin (and the customer
--     is told) instead of vanishing; the admin refunds it in the Razorpay dashboard and records the reference. A failed / abandoned payment captures
--     nothing and creates no order and no stock movement, so there is nothing to undo.
--
-- NOT changed: analytics, product_stats, customer_stats and profiles.total_* stay GROSS (D-15); orders.payment_status is not extended.
-- HOW TO RUN: SQL Editor -> paste -> Run (after M5b). SAFE TO RE-RUN. Rollback: 20261017_08_rollback.sql (run it BEFORE M5b's rollback).
-- ROLL-OUT ORDER: SQL first, then the website, then the RN app. No Edge Function changes.
-- ============================================================================
begin;

