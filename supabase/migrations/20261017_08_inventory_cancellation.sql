-- 2 -- record_inspection (M4b) + the stock hook ------------------------------------------------------------------------------------------------
-- Same function as M4b with one addition: each result may carry `disposition` (restock | unsellable | none; see the header). The default is
-- restock for a passed line and unsellable for a failed one. A passed line cannot be "none" (it is refunded / exchanged, so it is ours) and a
-- failed line cannot be "restock" (we did not accept it).
create or replace function public.record_inspection(p_request_id uuid, p_results jsonb, p_internal_note text default null)
returns jsonb
language plpgsql security definer
set search_path = public, pg_catalog
as $$
declare
  v_uid  uuid := auth.uid();
  r      public.return_requests;
  d      jsonb;
  v_iid  uuid;
  v_res  text;
  v_note text;
  v_disp text;
  it     public.return_request_items;
  v_seen uuid[] := '{}';
  v_wait integer;
  v_pass integer;
  v_fail integer;
begin
  r := public.app_lock_request_for_admin(p_request_id);
  if r.status <> 'inspection_pending' then raise exception 'Only a request that is waiting for inspection can be inspected (this one is "%")', replace(r.status, '_', ' ') using errcode = '22023'; end if;
  if p_results is null or jsonb_typeof(p_results) <> 'array' or jsonb_array_length(p_results) = 0 then raise exception 'Record a result for at least one item' using errcode = '22023'; end if;
  for d in select e.value from jsonb_array_elements(p_results) as e loop
    begin
      v_iid := (d ->> 'item_id')::uuid;
    exception when others then
      raise exception 'Each result needs a valid item_id' using errcode = '22023';
    end;
    v_res := d ->> 'result';
    v_note := nullif(btrim(coalesce(d ->> 'note', '')), '');
    v_disp := nullif(lower(btrim(coalesce(d ->> 'disposition', ''))), '');
    if v_res is null or v_res not in ('passed', 'failed') then raise exception 'The result must be passed or failed' using errcode = '22023'; end if;
    if v_iid = any (v_seen) then raise exception 'An item appears twice in the results' using errcode = '22023'; end if;
    v_seen := v_seen || v_iid;
    select * into it from public.return_request_items where id = v_iid and request_id = p_request_id for update;
    if not found then raise exception 'Item % is not part of this request', v_iid using errcode = '22023'; end if;
    if it.item_status <> 'received' then raise exception 'This item cannot be inspected (it is "%")', it.item_status using errcode = '22023'; end if;
    if v_res = 'failed' and v_note is null then raise exception 'Tell the customer why the item failed the inspection' using errcode = '22023'; end if;
    -- where the returned units go
    if v_disp is null then v_disp := case when v_res = 'passed' then 'restock' else 'unsellable' end; end if;
    if v_res = 'passed' and v_disp not in ('restock', 'unsellable') then
      raise exception 'An accepted item is either put back on sale ("restock") or kept as not resellable ("unsellable")' using errcode = '22023', detail = 'BAD_DISPOSITION';
    end if;
    if v_res = 'failed' and v_disp not in ('unsellable', 'none') then
      raise exception 'A rejected item is either kept as not resellable ("unsellable") or not recorded in stock ("none", e.g. sent back to the customer)' using errcode = '22023', detail = 'BAD_DISPOSITION';
    end if;
    update public.return_request_items set item_status = v_res, inspection_note = v_note, inspected_at = now(), disposition = v_disp where id = v_iid;
    insert into public.return_request_events (request_id, item_id, actor_id, actor_role, note)
    values (p_request_id, v_iid, v_uid, 'admin', 'Inspection ' || v_res || coalesce(': ' || v_note, ''));
    perform public.app_after_inspection(v_iid, v_res);
  end loop;
  if nullif(btrim(coalesce(p_internal_note, '')), '') is not null then
    insert into public.return_request_events (request_id, actor_id, actor_role, note, internal) values (p_request_id, v_uid, 'admin', btrim(p_internal_note), true);
  end if;
  select count(*) filter (where item_status = 'received'), count(*) filter (where item_status = 'passed'), count(*) filter (where item_status = 'failed')
    into v_wait, v_pass, v_fail from public.return_request_items where request_id = p_request_id;
  if v_wait = 0 then
    r := public.app_apply_request_transition(p_request_id, case when v_pass > 0 then 'inspection_passed' else 'inspection_failed' end, 'system', v_uid, null,
           case when v_pass > 0 and v_fail > 0 then v_pass || ' item(s) accepted, ' || v_fail || ' not accepted.'
                when v_pass > 0 then 'All returned items were accepted.' else 'The returned items could not be accepted.' end, true);
  else
    select * into r from public.return_requests where id = p_request_id;
  end if;
  return jsonb_build_object('ok', true, 'status', r.status, 'passed', v_pass, 'failed', v_fail, 'waiting', v_wait);
end;
$$;

-- the hook record_inspection calls after each line (a no-op in M4b): the returned units go to the counter / bucket the disposition names.
-- Never raises for a missing product (the units are then simply not recorded); a repeat call changes nothing.
create or replace function public.app_after_inspection(p_item_id uuid, p_result text)
returns void
language plpgsql security definer
set search_path = public, pg_catalog
as $$
declare
  it      public.return_request_items;
  rq      public.return_requests;
  oi      public.order_items;
  v_disp  text;
  v_eff   text;
  v_after integer;
  v_why   text;
begin
  select * into it from public.return_request_items where id = p_item_id;
  if not found or it.stock_effect is not null then return; end if;                 -- unknown line, or already recorded (a retry)
  select * into rq from public.return_requests where id = it.request_id;
  select * into oi from public.order_items where id = it.order_item_id;
  if oi.id is null then return; end if;
  v_disp := coalesce(it.disposition, case when p_result = 'passed' then 'restock' else 'unsellable' end);
  v_why := rq.request_no || case when rq.type = 'exchange' then ' (exchange)' else ' (return)' end;

  begin
    if v_disp = 'restock' then
      v_after := public.apply_inventory_movement(oi.product_id, coalesce(oi.variant_id, ''), it.quantity, 'return_restock', rq.order_id, 'return_request_item', it.id::text,
                   'Returned item accepted and put back on sale: ' || v_why, auth.uid(), case when auth.uid() is null then 'system' else 'admin' end, 'retrestock:' || it.id::text);
      v_eff := case when v_after is null then 'none' else 'restocked' end;           -- NULL = the option does not track inventory
    elsif v_disp = 'unsellable' then
      perform public.apply_inventory_movement(oi.product_id, coalesce(oi.variant_id, ''), it.quantity, 'return_unsellable', rq.order_id, 'return_request_item', it.id::text,
                   'Returned item kept as not resellable: ' || v_why, auth.uid(), case when auth.uid() is null then 'system' else 'admin' end, 'retunsell:' || it.id::text, 'unsellable');
      v_eff := 'unsellable';
    else
      v_eff := 'none';
    end if;
  exception when sqlstate 'P0002' then
    v_eff := 'none';                                                                -- the product / variant no longer exists: nothing to record against
    raise warning 'returned item % has no stock record: %', it.id, sqlerrm;
  end;
  update public.return_request_items set stock_effect = v_eff where id = it.id;
end;
$$;

-- 3 -- stock reports (admin only) ----------------------------------------------------------------------------------------------------------------
-- the sellable counter vs what the LEDGER says it should be after its last movement. drift <> 0 = stock was changed without a ledger row
-- (a direct SQL edit, a legacy path). Options that never had a ledger row with stock_after are not listed (nothing to compare).
create or replace function public.inventory_reconcile(p_only_drift boolean default true)
returns table (product_id text, variant_id text, title text, variant_name text, actual_stock integer, ledger_stock integer, drift integer, movements bigint, last_movement_at timestamptz)
language plpgsql stable security definer
set search_path = public, pg_catalog
as $$
#variable_conflict use_column
begin
  if auth.uid() is null or not public.app_is_admin() then raise exception 'Admin access required' using errcode = '42501'; end if;
  return query
  with last_row as (
    select distinct on (l.product_id, l.variant_id) l.product_id, l.variant_id, l.stock_after, l.created_at
      from public.inventory_logs l where l.bucket = 'sellable' and l.stock_after is not null
     order by l.product_id, l.variant_id, l.seq desc
  ), cnt as (
    select l.product_id, l.variant_id, count(*) as n from public.inventory_logs l where l.bucket = 'sellable' and l.stock_after is not null group by l.product_id, l.variant_id
  ), joined as (
    select lr.product_id, lr.variant_id, p.title, v.name as variant_name,
           (case when lr.variant_id = '' then p.stock else v.stock end)::integer as actual_stock, lr.stock_after as ledger_stock, cnt.n as movements, lr.created_at
      from last_row lr
      join cnt on cnt.product_id = lr.product_id and cnt.variant_id = lr.variant_id
      join public.products p on p.id = lr.product_id
      left join public.product_variants v on v.id = lr.variant_id and v.product_id = lr.product_id
     where lr.variant_id = '' or v.id is not null
  )
  select j.product_id, j.variant_id, j.title, j.variant_name, j.actual_stock, j.ledger_stock, (j.actual_stock - j.ledger_stock)::integer, j.movements, j.created_at
    from joined j
   where not p_only_drift or j.actual_stock <> j.ledger_stock
   order by abs(j.actual_stock - j.ledger_stock) desc, j.title, j.variant_name;
end;
$$;

-- every place where two consecutive sellable ledger rows of an option do not follow each other (stock_after - change <> the previous stock_after)
create or replace function public.inventory_gaps(p_limit integer default 200)
returns table (product_id text, variant_id text, seq bigint, created_at timestamptz, movement_type text, change integer, previous_after integer, stock_after integer, missing integer)
language plpgsql stable security definer
set search_path = public, pg_catalog
as $$
#variable_conflict use_column
begin
  if auth.uid() is null or not public.app_is_admin() then raise exception 'Admin access required' using errcode = '42501'; end if;
  return query
  select g.product_id, g.variant_id, g.seq, g.created_at, g.movement_type, g.change, g.previous_after, g.stock_after, ((g.stock_after - g.change) - g.previous_after)::integer
    from (
      select l.product_id, l.variant_id, l.seq, l.created_at, l.movement_type, l.change, l.stock_after,
             lag(l.stock_after) over (partition by l.product_id, l.variant_id order by l.seq) as previous_after
        from public.inventory_logs l where l.bucket = 'sellable' and l.stock_after is not null
    ) g
   where g.previous_after is not null and (g.stock_after - g.change) <> g.previous_after
   order by g.seq desc
   limit greatest(1, least(coalesce(p_limit, 200), 1000));
end;
$$;

-- units kept as NOT resellable, per option (the `unsellable` bucket never feeds the sellable counter)
create or replace function public.inventory_unsellable_summary()
returns table (product_id text, variant_id text, title text, variant_name text, units bigint, movements bigint, last_movement_at timestamptz)
language plpgsql stable security definer
set search_path = public, pg_catalog
as $$
#variable_conflict use_column
begin
  if auth.uid() is null or not public.app_is_admin() then raise exception 'Admin access required' using errcode = '42501'; end if;
  return query
  select l.product_id, l.variant_id, p.title, v.name, sum(l.change)::bigint, count(*), max(l.created_at)
    from public.inventory_logs l
    join public.products p on p.id = l.product_id
    left join public.product_variants v on v.id = l.variant_id and v.product_id = l.product_id
   where l.bucket = 'unsellable'
   group by l.product_id, l.variant_id, p.title, v.name
  having sum(l.change) <> 0
   order by sum(l.change) desc, p.title;
end;
$$;

