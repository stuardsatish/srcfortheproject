#!/usr/bin/env node
// Builds the single-file "Dashboard bundle" of an Edge Function from its source.
//
//   node supabase/bundle-functions.mjs payment-create-order payment-cod-create
//   node supabase/bundle-functions.mjs --all
//   node supabase/bundle-functions.mjs --out <dir> <function...>   (write elsewhere)
//
// The Supabase Dashboard's "Deploy a new function" editor takes one file, but
// the sources in functions/ share code through ../_shared/*.ts. This inlines
// those modules (dependencies first), strips the relative imports/exports and
// merges the `npm:` imports, so the pasted file is exactly what the CLI would
// deploy. Never edit the generated bundles by hand — change functions/ and
// re-run this.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const FUNCTIONS = path.join(here, "functions");
const BUNDLES = path.join(here, "dashboard-bundles");

// function folder -> bundle file name, where the historic name differs
const BUNDLE_NAME = { "payment-webhook": "payment-webhooks", "orders-bulk-import": "orders-bulk-imports" };

const IMPORT_RE = /^import\s+(type\s+)?([\s\S]*?)\s+from\s+["']([^"']+)["'];?[ \t]*\r?\n/gm;

function parseNamed(spec) {
    // "{ a, type b }" -> [{ name:'a', type:false }, { name:'b', type:true }]
    const m = spec.match(/^\{([\s\S]*)\}$/);
    if (!m) return null;
    return m[1].split(",").map((s) => s.trim()).filter(Boolean).map((s) => {
        const isType = /^type\s+/.test(s);
        return { name: s.replace(/^type\s+/, ""), type: isType };
    });
}

function bundle(fnName) {
    const entry = path.join(FUNCTIONS, fnName, "index.ts");
    if (!fs.existsSync(entry)) throw new Error(`No such function: ${fnName}`);

    const seen = new Set();
    const order = []; // [{ label, code }]
    const external = new Map(); // module -> { named: Map(name -> isTypeOnly), defaultName }
    // a module written in the plain-JavaScript subset of TypeScript starts with `// @ts-nocheck` (e.g. _shared/refundGateway.ts: its tests also run
    // in a browser without Node). Inlined into a bundle the comment would no longer be the file's first line, so it is hoisted to the bundle's top.
    let nocheck = false;

    const visit = (file, label) => {
        const abs = path.resolve(file);
        if (seen.has(abs)) return;
        seen.add(abs);
        let src = fs.readFileSync(abs, "utf8").replace(/^﻿/, "");

        const deps = [];
        if (/^\s*\/\/\s*@ts-nocheck\b/.test(src)) {
            nocheck = true;
            src = src.replace(/^\s*\/\/\s*@ts-nocheck\b[^\r\n]*\r?\n/, "");
        }
        src = src.replace(IMPORT_RE, (full, typeKw, spec, mod) => {
            if (mod.startsWith(".")) {
                deps.push(path.resolve(path.dirname(abs), mod));
                return "";
            }
            const entryFor = external.get(mod) || { named: new Map(), defaultName: null };
            const named = parseNamed(spec);
            if (named) {
                for (const n of named) {
                    const typeOnly = !!typeKw || n.type;
                    // a name imported as a value anywhere must be a value import
                    entryFor.named.set(n.name, (entryFor.named.get(n.name) ?? true) && typeOnly);
                }
            } else {
                entryFor.defaultName = spec.trim();
            }
            external.set(mod, entryFor);
            return "";
        });

        for (const d of deps) visit(d, path.basename(d));

        src = src
            .replace(/^export\s+\{[^}]*\};?[ \t]*\r?\n/gm, "")
            .replace(/^export\s+(async\s+function|function|const|let|class|type|interface)\b/gm, "$1")
            .replace(/\r\n/g, "\n")
            .trim();
        order.push({ label, code: src });
    };

    visit(entry, "function logic (index.ts)");

    const head = [];
    for (const [mod, e] of external) {
        const parts = [];
        if (e.defaultName) parts.push(e.defaultName);
        if (e.named.size) {
            const names = [...e.named].map(([n, typeOnly]) => (typeOnly ? `type ${n}` : n));
            parts.push(`{ ${names.join(", ")} }`);
        }
        head.push(`import ${parts.join(", ")} from "${mod}";`);
    }

    const out = [
        "// ============================================================================",
        `// ${fnName} — SELF-CONTAINED Dashboard bundle.`,
        "// GENERATED by supabase/bundle-functions.mjs from supabase/functions/ — do not edit by hand.",
        `// Paste this whole file as the function's index.ts in the Supabase Dashboard`,
        `// (Edge Functions -> Deploy a new function -> name it "${fnName}").`,
        "// ============================================================================",
        ...(nocheck ? ["// @ts-nocheck", "// (this bundle contains a module written in the plain-JavaScript subset of TypeScript; the sources under functions/ are type-checked as usual)"] : []),
        ...head,
        "",
    ];
    for (const m of order) {
        out.push(`/* ============================== ${m.label} ============================== */`, m.code, "");
    }
    return out.join("\n");
}

const args = process.argv.slice(2);
let outDir = BUNDLES;
const oi = args.indexOf("--out");
if (oi !== -1) { outDir = path.resolve(args[oi + 1]); args.splice(oi, 2); }
let names = args;
if (args.includes("--all")) {
    names = fs.readdirSync(FUNCTIONS, { withFileTypes: true })
        .filter((d) => d.isDirectory() && d.name !== "_shared").map((d) => d.name);
}
if (!names.length) { console.error("usage: node supabase/bundle-functions.mjs [--out dir] <function...|--all>"); process.exit(1); }
fs.mkdirSync(outDir, { recursive: true });
for (const n of names) {
    const text = bundle(n);
    const file = path.join(outDir, `${BUNDLE_NAME[n] || n}.ts`);
    fs.writeFileSync(file, text);
    console.log(`wrote ${path.relative(process.cwd(), file)} (${text.split("\n").length} lines)`);
}